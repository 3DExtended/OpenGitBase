#!/usr/bin/env bash
#
# Regression test: Docker restarts the API and ComputeAgent containers when their .NET process
# aborts on an unhandled exception, and `docker stop` still shuts them down gracefully.
#
# With `ENTRYPOINT ["dotnet", ...]` dotnet is PID 1 of the container. The kernel drops
# default-action signals sent to a PID namespace's init, so the SIGABRT the runtime raises on an
# unhandled exception does not end the process: the container keeps running (the API even stays
# healthy) with RestartCount 0 and `restart: unless-stopped` never fires. The images run dotnet
# under tini.
#
# The check runs the real docker-compose.yml services in a compose project of its own (postgres,
# redis, api-1, compute-agent-1; no Kafka, MinIO, storage or published ports) and makes the .NET
# process throw on a background thread through a startup hook mounted only here, so the images
# under test are the ones that ship.
#
# Usage:
#   scripts/test-dotnet-abort-restart.sh               # build both images, then check
#   SKIP_BUILD=1 scripts/test-dotnet-abort-restart.sh  # reuse the images from an earlier run
#
# Requires: docker with Compose v2.24+ (!reset / !override in the overlay)

set -euo pipefail

SCRIPT_DIR=$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)
REPO_ROOT=$(cd "${SCRIPT_DIR}/.." && pwd)
# shellcheck source=docker-env.sh
source "${SCRIPT_DIR}/docker-env.sh"

PROJECT="ogb-abort-restart-$$"
# Own tags, so the run never replaces the opengitbase-api / -compute-agent images a stack uses.
API_IMAGE="opengitbase-api:abort-restart-check"
COMPUTE_AGENT_IMAGE="opengitbase-compute-agent:abort-restart-check"
SDK_IMAGE="mcr.microsoft.com/dotnet/sdk:10.0"
TRIGGER_FILE="/tmp/ogb-abort-restart-trigger"
ABORT_MESSAGE="ogb abort-restart check: unhandled exception on a background thread"
WAIT_SECONDS="${WAIT_SECONDS:-60}"
WAIT_TIMEOUT="${WAIT_TIMEOUT:-180}"
# Compose's default stop_grace_period; neither service sets its own.
STOP_GRACE_SECONDS=10

TMP=""
STACK_STARTED=false
FAILURES=0

cleanup() {
  if [ "${STACK_STARTED}" = "true" ]; then
    # rm -v removes only the containers' anonymous volumes, never a named volume.
    compose rm -f -s -v >/dev/null 2>&1 || true
    compose down --remove-orphans >/dev/null 2>&1 || true
  fi
  if [ -n "${TMP}" ] && [ -d "${TMP}" ]; then
    rm -rf "${TMP}"
  fi
}
trap cleanup EXIT

pass() {
  echo "    ok: $*"
}

fail() {
  echo "    FAIL: $*" >&2
  FAILURES=$((FAILURES + 1))
}

compose() {
  docker compose -p "${PROJECT}" \
    -f "${REPO_ROOT}/docker-compose.yml" \
    -f "${TMP}/docker-compose.abort-restart.yml" \
    "$@"
}

# Captured whole: `docker logs | grep -q` fails under pipefail when grep exits early.
container_logs() {
  docker logs "$1" 2>&1 || true
}

show_logs() {
  container_logs "$1" | tail -n 25 | sed 's/^/      /' >&2
}

inspect() {
  docker inspect -f "$2" "$1" 2>/dev/null || echo missing
}

health_status() {
  inspect "$1" '{{if .State.Health}}{{.State.Health.Status}}{{else}}none{{end}}'
}

wait_healthy() {
  local container="$1" i
  for i in $(seq 1 "${WAIT_TIMEOUT}"); do
    if [ "$(health_status "${container}")" = "healthy" ]; then
      return 0
    fi
    sleep 1
  done
  return 1
}

# The startup hook starts a thread that throws once TRIGGER_FILE exists. It deletes the file
# first: a restart keeps the container's filesystem, and the restarted process must stay up.
write_startup_hook() {
  mkdir -p "${TMP}/hook"
  cat >"${TMP}/hook/AbortStartupHook.csproj" <<'EOF'
<Project Sdk="Microsoft.NET.Sdk">
  <PropertyGroup>
    <TargetFramework>net10.0</TargetFramework>
    <Nullable>enable</Nullable>
  </PropertyGroup>
</Project>
EOF
  cat >"${TMP}/hook/StartupHook.cs" <<EOF
using System;
using System.IO;
using System.Threading;

internal static class StartupHook
{
    public static void Initialize()
    {
        new Thread(() =>
        {
            while (!File.Exists("${TRIGGER_FILE}"))
            {
                Thread.Sleep(200);
            }

            File.Delete("${TRIGGER_FILE}");
            throw new InvalidOperationException("${ABORT_MESSAGE}");
        })
        {
            IsBackground = true,
            Name = "abort-restart-check",
        }.Start();
    }
}
EOF
}

build_startup_hook() {
  docker run --rm --user "$(id -u):$(id -g)" \
    -e HOME=/tmp -e DOTNET_CLI_TELEMETRY_OPTOUT=1 -e DOTNET_NOLOGO=1 \
    -v "${TMP}/hook:/hook" -w /hook \
    "${SDK_IMAGE}" dotnet build -c Release -o /hook/out -v quiet >/dev/null
}

write_overlay() {
  cat >"${TMP}/docker-compose.abort-restart.yml" <<EOF
# Generated by scripts/test-dotnet-abort-restart.sh for compose project ${PROJECT}.
x-abort-hook: &abort-hook
  DOTNET_STARTUP_HOOKS: /abort-hook/AbortStartupHook.dll

services:
  postgres:
    container_name: !reset null
    ports: !reset []
    volumes: !reset []
  redis:
    container_name: !reset null
    ports: !reset []
  api-1:
    image: ${API_IMAGE}
    container_name: !reset null
    depends_on: !override
      postgres:
        condition: service_healthy
      redis:
        condition: service_started
    environment:
      <<: *abort-hook
      # No Kafka here; the topic and consumer services skip without bootstrap servers.
      Kafka__BootstrapServers: ""
    volumes:
      - ${TMP}/hook/out:/abort-hook:ro
  compute-agent-1:
    image: ${COMPUTE_AGENT_IMAGE}
    container_name: !reset null
    # The agent keeps retrying its registration while api-lb is unreachable.
    depends_on: !reset {}
    environment:
      <<: *abort-hook
    volumes:
      - ${TMP}/hook/out:/abort-hook:ro
EOF
}

service_container() {
  compose ps -a -q "$1"
}

# Makes the service's .NET process throw on a background thread and checks that the process
# died of SIGABRT (exit 134) and Docker restarted the container.
check_abort_restarts() {
  local service="$1" needs_health="$2"
  local container restarts_before since i restarts exit_code
  container="$(service_container "${service}")"

  restarts_before="$(inspect "${container}" '{{.RestartCount}}')"
  if [ "${restarts_before}" != "0" ]; then
    fail "${service} restarted ${restarts_before} time(s) before the check; it does not stay up here"
    show_logs "${container}"
    return
  fi

  since="$(date +%s)"
  compose exec -T "${service}" touch "${TRIGGER_FILE}"

  restarts="${restarts_before}"
  for i in $(seq 1 "${WAIT_SECONDS}"); do
    restarts="$(inspect "${container}" '{{.RestartCount}}')"
    if [ "${restarts}" != "${restarts_before}" ]; then
      break
    fi
    sleep 1
  done

  if ! grep -qF "Unhandled exception. System.InvalidOperationException: ${ABORT_MESSAGE}" \
    <<<"$(container_logs "${container}")"; then
    fail "${service}: the startup hook's exception never reached the logs; nothing was aborted"
    show_logs "${container}"
    return
  fi

  if [ "${restarts}" = "${restarts_before}" ]; then
    fail "${service}: the .NET process hit an unhandled exception, but Docker did not restart" \
      "the container within ${WAIT_SECONDS}s (status $(inspect "${container}" '{{.State.Status}}')," \
      "health $(health_status "${container}"), RestartCount ${restarts}, PID 1 is" \
      "$(docker exec "${container}" cat /proc/1/comm 2>/dev/null || echo unknown))"
    show_logs "${container}"
    return
  fi
  pass "${service}: Docker restarted the container after the unhandled exception"

  # --until is exclusive to the nanosecond, so a die in the current second needs the next one.
  exit_code="$(docker events --since "${since}" --until "$(($(date +%s) + 1))" \
    --filter "container=${container}" --filter event=die \
    --format '{{index .Actor.Attributes "exitCode"}}' | sed -n 1p)"
  if [ "${exit_code}" = "134" ]; then
    pass "${service}: the process exited with 134 (SIGABRT)"
  else
    fail "${service}: expected exit code 134 (SIGABRT), the container died with '${exit_code}'"
  fi

  if [ "${needs_health}" = "true" ]; then
    if wait_healthy "${container}"; then
      pass "${service}: healthy again after the restart"
    else
      fail "${service}: not healthy within ${WAIT_TIMEOUT}s of the restart"
      show_logs "${container}"
    fi
  fi
}

# `docker stop` must reach the .NET host: it logs the shutdown and exits 0 within the grace
# period instead of being killed (137) when it runs out.
check_graceful_stop() {
  local service="$1"
  local container started elapsed exit_code shutdown_logs
  container="$(service_container "${service}")"

  started="$(date +%s)"
  compose stop -t "${STOP_GRACE_SECONDS}" "${service}" >/dev/null 2>&1
  elapsed=$(($(date +%s) - started))
  exit_code="$(inspect "${container}" '{{.State.ExitCode}}')"

  if [ "${exit_code}" = "0" ] && [ "${elapsed}" -lt "${STOP_GRACE_SECONDS}" ]; then
    pass "${service}: docker stop exited 0 after ${elapsed}s"
  else
    fail "${service}: docker stop took ${elapsed}s (grace ${STOP_GRACE_SECONDS}s), exit code ${exit_code}"
  fi

  shutdown_logs="$(container_logs "${container}" | sed -n '/Application is shutting down\.\.\./,$p')"
  if [ -z "${shutdown_logs}" ]; then
    fail "${service}: no 'Application is shutting down...' in the logs; SIGTERM did not reach dotnet"
    show_logs "${container}"
  elif grep -qE '^(fail|crit): ' <<<"${shutdown_logs}"; then
    fail "${service}: errors were logged while the hosted services stopped"
    sed -n '1,25{s/^/      /;p;}' <<<"${shutdown_logs}" >&2
  else
    pass "${service}: the host logged its shutdown and no errors"
  fi
}

TMP="$(mktemp -d "${TMPDIR:-/tmp}/ogb-abort-restart.XXXXXX")"
TMP="$(cd "${TMP}" && pwd -P)"

echo "==> Build the abort startup hook (${SDK_IMAGE})"
write_startup_hook
build_startup_hook
write_overlay

if [ "${SKIP_BUILD:-0}" != "1" ]; then
  echo "==> Build ${API_IMAGE} and ${COMPUTE_AGENT_IMAGE}"
  compose build api-1 compute-agent-1
fi

echo "==> Start postgres, redis, api-1 and compute-agent-1 (project ${PROJECT})"
STACK_STARTED=true
if ! compose up -d --wait --wait-timeout "${WAIT_TIMEOUT}" postgres redis api-1 compute-agent-1; then
  echo "error: the services did not come up" >&2
  compose logs --tail 40 api-1 compute-agent-1 >&2 || true
  exit 1
fi
# The agent has no healthcheck; give it time to fail at startup if it is going to.
sleep 5

echo "==> docker stop shuts the API down gracefully"
check_graceful_stop api-1

echo "==> docker stop shuts the compute agent down gracefully"
check_graceful_stop compute-agent-1

echo "==> Start api-1 and compute-agent-1 again"
compose start api-1 compute-agent-1 >/dev/null
if ! wait_healthy "$(service_container api-1)"; then
  echo "error: api-1 did not become healthy again" >&2
  show_logs "$(service_container api-1)"
  exit 1
fi
sleep 5

echo "==> Unhandled exception in the API restarts the container"
check_abort_restarts api-1 true

echo "==> Unhandled exception in the compute agent restarts the container"
check_abort_restarts compute-agent-1 false

echo ""
if [ "${FAILURES}" -gt 0 ]; then
  echo "${FAILURES} check(s) failed." >&2
  exit 1
fi
echo "All checks passed."
